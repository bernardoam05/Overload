Future<void> seedRoutines(AppDatabase db) async {
  final rows = await db.select(db.exercises).get();
  final byKey = {
    for (final e in rows)
      if (e.seedKey != null) e.seedKey!: e.id,
  };
  final now = DateTime.now();
  for (final (i, (name, items)) in _routineSeed.indexed) {
    final id = await db
        .into(db.routines)
        .insert(
          RoutinesCompanion.insert(
            name: name,
            position: Value(i),
            createdAt: now,
          ),
        );
    await db.batch((b) {
      b.insertAll(db.routineExercises, [
        for (final (j, (key, sets, reps)) in items.indexed)
          if (byKey[key] != null)
            RoutineExercisesCompanion.insert(
              routineId: id,
              exerciseId: byKey[key]!,
              position: j,
              sets: Value(sets),
              reps: Value(reps),
            ),
      ]);
    });
  }
}
